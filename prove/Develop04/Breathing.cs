using System.Diagnostics;

public class Breathing : Activity
{
  public Breathing() : base(
    "Breathing Exercise",
    
    """
    Consciously controlling your breath rate is one of the
    only ways to excise control of your heart rate. It is
    helpful for grounding you in present reality, and can
    help calm a disrupted system.

    This exercise will show a graphic to help you time and
    control your breaths. Follow along for the duration of
    the activity.
    """,

    """
    1.  2 minutes
    2.  5 minutes
    3. 8 minutes
    """,
    ["2 minute", "4 minute", "8 minute"],
    [0, 1, 2]
    // For this activity the time values are indices for the animation option list.
  )
  {
    
  }
  
  private void Middle(int pick)
  {
    Animation.Run(pick);
  }

  public void Run()
  {
    base.Begin();
    Middle(_durationValue);
    base.End();
    
    Console.WriteLine(
    "\n\n\n" + 
    "Complete\n\n" +
    "████████████████████████████████████████████████"
    );
  }

  

  // Helper to Breathing class. It really should only be accessible to the
  // breathing activity, and nesting was the only way I could figure out how to 
  // accomplish this.
  protected class Animation
  { 
    public static void Run(int value)
    {
      foreach (string bar in _progressFrames[value])
      {
        Loop(bar);
      }
    }

    private static void Loop(string progress)
    // One full loop takes 20 seconds. (3 loops per minute)
    {
      // Inhale. Lasts 8 frames, should take 4 seconds.
      for (int i = 0; i < 8; i++)
      {
        Support.Clear();
        Console.WriteLine(Animation._breathFrames[i]);
        Console.WriteLine(progress);
        Thread.Sleep(250);
      }
      // First hold
      for (int i = 8; i < 11; i++)
      {
        Support.Clear();
        Console.WriteLine(Animation._breathFrames[i]);
        Console.WriteLine(progress);
        Thread.Sleep(1000);
      }
      // Exhale. Lasts 59 frames, should be about 10 seconds.
      for (int i = 11; i < 70; i++)
      {
        Support.Clear();
        Console.WriteLine(Animation._breathFrames[i]);
        Console.WriteLine(progress);
        Thread.Sleep(10000/59);
      }
      // Final hold. Lasts for 45 frames, should be 3 seconds
      for (int i = 70; i < 115; i++)
      {
        Support.Clear();
        Console.WriteLine(Animation._breathFrames[i]);
        Console.WriteLine(progress);
        Thread.Sleep(3000/45);
      }
    }

